import 'package:flutter/services.dart';
import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;

import '../models.dart';
import 'formatting.dart';

PdfPageFormat salesReportPageFormat(SalesReport report) {
  const mm = PdfPageFormat.mm;
  final height =
      (118 + report.paymentMethods.length * 9 + report.itemsSold.length * 11)
          .clamp(150, 3000) *
      mm;
  return PdfPageFormat(80 * mm, height, marginAll: 4 * mm);
}

Future<Uint8List> buildSalesReportPdf(SalesReport report) async {
  final logo = pw.MemoryImage(
    (await rootBundle.load('assets/images/wrw-dark.png')).buffer.asUint8List(),
  );
  final document = pw.Document();
  document.addPage(
    pw.Page(
      pageFormat: salesReportPageFormat(report),
      build: (context) => pw.Column(
        crossAxisAlignment: pw.CrossAxisAlignment.stretch,
        children: [
          pw.Center(
            child: pw.Image(
              logo,
              width: 42 * PdfPageFormat.mm,
              height: 14 * PdfPageFormat.mm,
            ),
          ),
          pw.SizedBox(height: 2 * PdfPageFormat.mm),
          _centered('SALES REPORT', bold: true, fontSize: 12),
          pw.SizedBox(height: 3 * PdfPageFormat.mm),
          _detail('Cashier', report.cashierName),
          _detail('Period', '${report.dateFrom} - ${report.dateTo}'),
          _detail('Printed', _formatTimestamp(DateTime.now())),
          pw.Divider(),
          _heading('SUMMARY', bold: true, fontSize: 8),
          _detail('Transactions', '${report.transactionCount}'),
          _detail('Total Sales', formatMoney(report.totalSales), bold: true),
          _detail('VAT', formatMoney(report.vat)),
          pw.SizedBox(height: 2 * PdfPageFormat.mm),
          _dottedDivider(),
          pw.SizedBox(height: 2 * PdfPageFormat.mm),
          _heading('PAYMENT BREAKDOWN', bold: true, fontSize: 8),
          if (report.paymentMethods.isEmpty)
            _detail('No payments recorded', '')
          else
            ...report.paymentMethods.map(
              (method) => _detail(method.name, formatMoney(method.amount)),
            ),
          pw.SizedBox(height: 2 * PdfPageFormat.mm),
          _dottedDivider(),
          pw.SizedBox(height: 2 * PdfPageFormat.mm),
          _heading('ITEMS SOLD', bold: true, fontSize: 8),
          if (report.itemsSold.isEmpty)
            _detail('No items sold', '')
          else
            ...report.itemsSold.map((item) => _itemRow(item)),
          pw.Divider(),
          _centered('End of Sales Report'),
          pw.SizedBox(height: 4 * PdfPageFormat.mm),
          _centered('Generated by WeRWines'),
        ],
      ),
    ),
  );
  return document.save();
}

pw.Widget _dottedDivider() => pw.Row(
  mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
  children: List.generate(
    36,
    (_) => pw.Container(
      width: 1,
      height: 1,
      decoration: const pw.BoxDecoration(
        color: PdfColors.grey600,
        shape: pw.BoxShape.circle,
      ),
    ),
  ),
);

pw.Widget _centered(String value, {bool bold = false, double fontSize = 9}) =>
    pw.Padding(
      padding: const pw.EdgeInsets.symmetric(vertical: 1),
      child: pw.Text(
        value,
        textAlign: pw.TextAlign.center,
        style: pw.TextStyle(
          fontSize: fontSize,
          fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
        ),
      ),
    );

pw.Widget _heading(String value, {bool bold = true, double fontSize = 9}) =>
    pw.Padding(
      padding: const pw.EdgeInsets.only(bottom: 2),
      child: pw.Text(
        value,
        style: pw.TextStyle(
          fontSize: fontSize,
          fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
        ),
      ),
    );

pw.Widget _detail(String label, String value, {bool bold = false}) {
  final style = pw.TextStyle(
    fontSize: 8,
    fontWeight: bold ? pw.FontWeight.bold : pw.FontWeight.normal,
  );
  return pw.Padding(
    padding: const pw.EdgeInsets.symmetric(vertical: 1.5),
    child: pw.Row(
      mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
      children: [
        pw.Expanded(child: pw.Text(label, style: style)),
        pw.SizedBox(width: 4),
        pw.Text(value, style: style, textAlign: pw.TextAlign.right),
      ],
    ),
  );
}

pw.Widget _itemRow(SalesReportItem item) => pw.Padding(
  padding: const pw.EdgeInsets.symmetric(vertical: 2),
  child: pw.Column(
    crossAxisAlignment: pw.CrossAxisAlignment.stretch,
    children: [
      pw.Text(
        item.name,
        style: pw.TextStyle(fontSize: 8,),
      ),
      pw.Row(
        mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
        children: [
          pw.Text(
            '${_formatQuantity(item.quantity)} ${item.priceType}',
            style: const pw.TextStyle(fontSize: 6),
          ),
          pw.Text(
            formatMoney(item.totalAmount),
            style: const pw.TextStyle(fontSize: 8, fontWeight: pw.FontWeight.bold),
          ),
        ],
      ),
    ],
  ),
);

String _formatQuantity(double quantity) =>
    quantity == quantity.truncateToDouble()
    ? quantity.toStringAsFixed(0)
    : quantity.toString();

String _formatTimestamp(DateTime date) =>
    '${date.day.toString().padLeft(2, '0')}/'
    '${date.month.toString().padLeft(2, '0')}/${date.year}, '
    '${date.hour.toString().padLeft(2, '0')}:'
    '${date.minute.toString().padLeft(2, '0')}';
